import type { Settings } from "./theme";

/** 界面语言。zh-CN 是源语言：词条表里不写它，key 本身就是简体中文文案
    （gettext 风格），其它语言查不到时回落 key，永远不会显示裸键名。 */
export type Lang = "zh-CN" | "zh-TW" | "en" | "ja" | "es";
export type LangSetting = Settings["language"];

export const SUPPORTED_LANGS: { id: LangSetting; label: string }[] = [
  { id: "system", label: "跟随系统" },
  { id: "zh-CN", label: "简体中文" },
  { id: "zh-TW", label: "繁體中文" },
  { id: "en", label: "English" },
  { id: "ja", label: "日本語" },
  { id: "es", label: "Español" },
];

let current: Lang = "zh-CN";

/** 把「系统/指定」的语言设置解析成实际语言。
    系统语言不在支持范围（如 ru/ko/de…）时按需求回落英语。 */
export function resolveLocale(setting: LangSetting): Lang {
  if (setting !== "system") return setting;
  const nav =
    typeof navigator !== "undefined" ? navigator.language || "" : "";
  const l = nav.toLowerCase();
  if (l.startsWith("zh")) {
    // zh-TW / zh-HK / zh-Hant* → 繁体；zh-CN / zh-SG / 裸 zh → 简体
    if (/(tw|hk|mo|hant)/.test(l)) return "zh-TW";
    return "zh-CN";
  }
  if (l.startsWith("ja")) return "ja";
  if (l.startsWith("es")) return "es";
  return "en";
}

/** App 每次渲染前调用：幂等，语言没变就不动 */
export function applyLang(setting: LangSetting): Lang {
  const next = resolveLocale(setting);
  if (next !== current) current = next;
  return next;
}

export function currentLang(): Lang {
  return current;
}

function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`,
  );
}

/** 翻译：key 就是简体中文原文。占位符用 {name}。 */
export function t(
  key: string,
  vars?: Record<string, string | number>,
): string {
  const dict = TABLE[current];
  const s = current === "zh-CN" ? key : (dict?.[key] ?? key);
  return interpolate(s, vars);
}

